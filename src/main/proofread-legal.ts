const q = (s: string) => JSON.stringify(s)
const toYaml = (rules: [string, string][]) =>
    `version: 1\nrules:\n${rules.map(([pattern, expected]) => `  - expected: ${q(expected)}\n    pattern: ${q(pattern)}\n`).join('')}`

